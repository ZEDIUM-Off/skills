#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const MARKER_START = '<!-- CANONICAL_LINE_REFERENCES_START -->'
const MARKER_END = '<!-- CANONICAL_LINE_REFERENCES_END -->'
const GENERATED_NOTE = '<!-- This block is generated by finalize-plan-lines.mjs. Do not edit manually. -->'
const ANCHOR_RE = /^<a id="([A-Za-z0-9][A-Za-z0-9._:-]*)"><\/a>\s*$/
const HEADING_RE = /^(#{1,6})\s+(.+?)\s*$/

function fail(message) {
  console.error(`finalize-plan-lines: ${message}`)
  process.exit(1)
}

const target = process.argv[2]
if (!target) {
  fail('usage: node finalize-plan-lines.mjs <plan.md>')
}

const path = resolve(process.cwd(), target)
let text
try {
  text = readFileSync(path, 'utf8')
} catch (error) {
  fail(`cannot read ${path}: ${error.message}`)
}

const startIndex = text.indexOf(MARKER_START)
const endIndex = text.indexOf(MARKER_END)
if (startIndex === -1 || endIndex === -1) {
  fail('canonical line reference markers are required')
}
if (text.indexOf(MARKER_START, startIndex + MARKER_START.length) !== -1) {
  fail('duplicate start marker')
}
if (text.indexOf(MARKER_END, endIndex + MARKER_END.length) !== -1) {
  fail('duplicate end marker')
}
if (endIndex <= startIndex) {
  fail('end marker must appear after start marker')
}

const lines = text.split(/\r?\n/)
const anchors = []
const seen = new Set()

for (let i = 0; i < lines.length; i += 1) {
  const match = lines[i].match(ANCHOR_RE)
  if (!match) continue

  const id = match[1]
  if (seen.has(id)) {
    fail(`duplicate anchor id: ${id}`)
  }
  seen.add(id)

  let headingLine = -1
  let headingLevel = null
  let headingText = ''
  for (let j = i + 1; j < Math.min(lines.length, i + 6); j += 1) {
    if (!lines[j].trim()) continue
    const heading = lines[j].match(HEADING_RE)
    if (!heading) {
      fail(`anchor ${id} is not followed by a heading within 5 lines`)
    }
    headingLine = j
    headingLevel = heading[1].length
    headingText = heading[2].trim()
    break
  }

  if (headingLine === -1) {
    fail(`anchor ${id} has no following heading`)
  }

  anchors.push({
    id,
    anchorLine: i,
    headingLine,
    headingLevel,
    headingText,
  })
}

if (anchors.length === 0) {
  fail('no anchors found')
}

const withRanges = anchors.map((anchor, index) => {
  let endLine = lines.length - 1
  for (let nextIndex = index + 1; nextIndex < anchors.length; nextIndex += 1) {
    const next = anchors[nextIndex]
    if (next.headingLevel <= anchor.headingLevel) {
      endLine = Math.max(anchor.anchorLine, next.anchorLine - 1)
      break
    }
  }

  while (endLine > anchor.anchorLine && !lines[endLine].trim()) {
    endLine -= 1
  }

  return {
    ...anchor,
    start: anchor.anchorLine + 1,
    end: endLine + 1,
  }
})

function escapeCell(value) {
  return String(value).replace(/\|/g, '\\|').replace(/\n/g, ' ')
}

const table = [
  GENERATED_NOTE,
  '| ID | Anchor | Lines | Description |',
  '|---|---|---|---|',
  ...withRanges.map((entry) => {
    const linesRange = entry.start === entry.end ? `L${entry.start}` : `L${entry.start}-L${entry.end}`
    return `| ${escapeCell(entry.id)} | #${escapeCell(entry.id)} | ${linesRange} | ${escapeCell(entry.headingText)} |`
  }),
].join('\n')

const before = text.slice(0, startIndex + MARKER_START.length)
const after = text.slice(endIndex)
const next = `${before}\n${table}\n${after}`

writeFileSync(path, next, 'utf8')
console.log(`Updated canonical line references for ${withRanges.length} anchors in ${path}`)
